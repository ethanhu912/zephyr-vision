"""Convert LaRS (COCO panoptic) to Ultralytics YOLO detection format.

Uses the per-segment bboxes in panoptic_annotations.json (no mask decoding). Keeps the
8 "thing" classes; drops stuff (static obstacle / water / sky).

Output: <dst>/{images,labels}/{train,val}/ + <dst>/lars.yaml. Images are hard-linked
from <src> (copied if linking fails).
"""

import argparse
import json
import os
import shutil
from collections import Counter
from pathlib import Path

# LaRS category_id -> (YOLO class, name). LaRS has no id 18.
LARS_TO_YOLO = {
    11: (0, "boat"),
    12: (1, "row_boat"),
    13: (2, "paddle_board"),
    14: (3, "buoy"),
    15: (4, "swimmer"),
    16: (5, "animal"),
    17: (6, "float"),
    19: (7, "other"),
}
NAMES = [name for _, name in sorted(LARS_TO_YOLO.values())]
SPLITS = ["train", "val"]  # test split has no public labels


def link_or_copy(src: Path, dst: Path) -> None:
    if dst.exists():
        return
    try:
        os.link(src, dst)
    except OSError:
        shutil.copy2(src, dst)


def convert_split(src: Path, dst: Path, split: str, skip_crowd: bool) -> Counter:
    ann = json.loads((src / split / "panoptic_annotations.json").read_text(encoding="utf-8"))
    images = {im["id"]: im for im in ann["images"]}

    img_out = dst / "images" / split
    lbl_out = dst / "labels" / split
    img_out.mkdir(parents=True, exist_ok=True)
    lbl_out.mkdir(parents=True, exist_ok=True)

    stats = Counter()
    for a in ann["annotations"]:
        im = images[a["image_id"]]
        W, H = im["width"], im["height"]
        img_path = src / split / "images" / im["file_name"]
        if not img_path.exists():
            raise FileNotFoundError(img_path)

        lines = []
        for seg in a["segments_info"]:
            if seg["category_id"] not in LARS_TO_YOLO:
                continue  # stuff class
            if skip_crowd and seg.get("iscrowd", 0):
                stats["skipped_crowd"] += 1
                continue
            cls, name = LARS_TO_YOLO[seg["category_id"]]
            x, y, w, h = seg["bbox"]  # COCO xywh, top-left origin, pixels
            x0, y0 = max(0.0, x), max(0.0, y)
            x1, y1 = min(float(W), x + w), min(float(H), y + h)
            if x1 <= x0 or y1 <= y0:
                stats["skipped_degenerate"] += 1
                continue
            xc, yc = (x0 + x1) / 2 / W, (y0 + y1) / 2 / H
            bw, bh = (x1 - x0) / W, (y1 - y0) / H
            lines.append(f"{cls} {xc:.6f} {yc:.6f} {bw:.6f} {bh:.6f}")
            stats[name] += 1

        link_or_copy(img_path, img_out / im["file_name"])
        # Write empty files too: Ultralytics treats them as background (negative) images.
        (lbl_out / (Path(im["file_name"]).stem + ".txt")).write_text(
            "\n".join(lines) + ("\n" if lines else "")
        )
        stats["images"] += 1
        stats["background_images"] += not lines
    return stats


def write_yaml(dst: Path) -> Path:
    yaml_path = dst / "lars.yaml"
    names = "\n".join(f"  {i}: {n}" for i, n in enumerate(NAMES))
    yaml_path.write_text(
        "# LaRS (Lakes, Rivers and Seas) obstacle detection, converted for YOLO.\n"
        "# Generated by scripts/convert_lars_to_yolo.py - re-run it on each machine.\n"
        "# License: CC BY-NC 4.0 (non-commercial; don't redistribute the files).\n"
        f"path: {dst.resolve().as_posix()}\n"
        "train: images/train\n"
        "val: images/val\n\n"
        f"names:\n{names}\n"
    )
    return yaml_path


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--src", type=Path, default=Path("datasets/lars_raw"))
    p.add_argument("--dst", type=Path, default=Path("datasets/lars_yolo"))
    p.add_argument("--skip-crowd", action="store_true",
                   help="drop iscrowd segments (mostly boat clusters) instead of keeping them as boxes")
    args = p.parse_args()

    for split in SPLITS:
        s = convert_split(args.src, args.dst, split, args.skip_crowd)
        per_class = ", ".join(f"{n}={s[n]}" for n in NAMES)
        print(f"[{split}] {s['images']} images ({s['background_images']} background) | {per_class}")
        for k in ("skipped_crowd", "skipped_degenerate"):
            if s[k]:
                print(f"         {k}: {s[k]}")
    print(f"wrote {write_yaml(args.dst)}")


if __name__ == "__main__":
    main()
